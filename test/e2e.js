/* End-to-end run of the built page in headless Chromium at phone size. Run: node test/e2e.js */
const fs = require('fs');
const path = require('path');
let pw;
try { pw = require('playwright'); } catch (e) { pw = require('/opt/npm-tools/node_modules/playwright'); }
const { chromium } = pw;

const URL = 'file://' + path.join(__dirname, '..', 'dist', 'test.html');
const SHOTS = path.join(__dirname, '..', 'shots');
fs.mkdirSync(SHOTS, { recursive: true });
const failures = [];
function check(cond, msg) { if (cond) console.log('  ✓ ' + msg); else { failures.push(msg); console.log('  ✗ ' + msg); } }

(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: 'dark', hasTouch: true, isMobile: true });
  const page = await ctx.newPage();
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error' && !/fonts\.(googleapis|gstatic)|ERR_|Failed to load resource/.test(m.text())) errors.push(m.text()); });
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));

  const act = (a, extra) => (a === 'closeSheet' && !extra ? page.click('.sheet-head [data-act="closeSheet"]') : page.click('[data-act="' + a + '"]' + (extra || '')));
  const app = () => page.textContent('#app');
  const sheet = () => page.textContent('#sheet');
  const score = () => page.textContent('.score');
  const wait = (ms) => page.waitForTimeout(ms);
  const shot = (n, full) => page.screenshot({ path: path.join(SHOTS, n + '.png'), fullPage: !!full });
  async function noOverflow(label) {
    const o = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    check(o <= 0, label + ': no horizontal overflow (' + o + 'px)');
  }
  const run = (n) => act('run', '[data-n="' + n + '"]');
  async function pickFirstEnabled() { await page.locator('#sheet .pick:not([disabled])').first().click(); }
  async function openers() {
    await page.locator('[data-act="opener"][data-k="striker"]:not([disabled])').first().click();
    await page.locator('[data-act="opener"][data-k="nonStriker"]:not([disabled]):not(.on)').first().click();
    await page.locator('[data-act="opener"][data-k="bowler"]:not([disabled])').first().click();
    await act('startInnings');
  }

  await page.goto(URL);
  console.log('Home');
  check((await app()).includes('Gully Cricket'), 'home renders brand');
  check(await page.isVisible('.steps'), 'first-run "how it works" shows tennis-ball tracker');
  await noOverflow('home');
  await shot('01-home');

  console.log('Teams');
  await act('newMatch');
  check((await page.inputValue('#nameA')) === 'Basavanagudi Bulls', 'example teams prefilled');
  await page.fill('#addA', 'Suresh, Ganesh');
  await page.press('#addA', 'Enter');
  check(await page.locator('.team:nth-of-type(1) .roster li').count() >= 7 || (await page.locator('.roster').first().locator('li').count()) === 7, 'comma list adds 2 players (7 total)');
  check(await page.evaluate(() => document.activeElement && document.activeElement.id === 'addA'), 'focus stays in the add field');
  await page.locator('.roster').first().locator('[data-act="rmPlayer"]').last().click();
  check((await page.locator('.roster').first().locator('li').count()) === 6, 'remove player works');
  await page.fill('#nameB', '');
  await act('toRules');
  check(await page.isVisible('.errors'), 'validation blocks empty team name');
  await page.fill('#nameB', 'Malleshwaram Mavericks');
  await noOverflow('teams');
  await shot('02-teams', true);
  await act('toRules');

  console.log('Rules');
  check((await app()).includes('Start from'), 'rules screen');
  await act('setNum', '[data-k="overs"][data-v="2"]');
  check((await page.textContent('.num-big')).trim() === '2', 'overs set to 2');
  await act('preset', '[data-v="tennis"]');
  check((await page.textContent('.num-big')).trim() === '6', 'tennis preset applies (6 overs)');
  await act('preset', '[data-v="gully"]');
  await act('setNum', '[data-k="overs"][data-v="2"]');
  await act('house', '[data-k="oneTip"]');
  await noOverflow('rules');
  await shot('03-rules', true);
  await act('toToss');

  console.log('Toss');
  await act('call', '[data-v="H"]'); await act('caller', '[data-v="A"]');
  await act('flip');
  await wait(400);
  await shot('04a-toss-flipping');
  await wait(1700);
  const tossTxt = await app();
  check(/won the toss/.test(tossTxt), 'coin flip decides a winner');
  await act('choice', '[data-v="bat"]');
  await noOverflow('toss');
  await shot('04-toss', true);
  await act('startMatch');

  console.log('Innings 1');
  check((await app()).includes('chose to'), 'openers screen shows toss line');
  await openers();
  check((await score()).replace(/\s/g, '') === '0/0', 'scoring starts at 0/0');
  await run(1); await run(4);
  await act('mod', '[data-k="wide"]');
  check((await page.textContent('.tracker-head.hint')).includes('Wide'), 'wide modifier hint shows in tracker');
  await act('out');
  const wideOuts = await page.locator('#sheet [data-act="how"]').count();
  check(wideOuts === 2, 'wide + OUT offers only stumped / run out (' + wideOuts + ')');
  await act('closeSheet');
  await run(0);
  check((await score()).replace(/\s/g, '') === '6/0', 'wide adds 1, re-bowled');
  check((await page.textContent('.overs b')).trim() === '0.2', 'wide does not count as a ball');
  await run(6);
  await shot('05-scoring');
  await act('out');
  await act('how', '[data-v="bowled"]');
  check((await sheet()).includes('Next batter'), 'wicket -> next batter sheet');
  await shot('05b-next-batter');
  await pickFirstEnabled();
  check((await score()).replace(/\s/g, '') === '12/1', 'score 12/1 after wicket');
  await run(0); await run(2);
  check((await sheet()).includes('Next bowler'), 'over end -> next bowler sheet');
  check(await page.locator('#sheet .pick[disabled]').count() === 1, 'last over bowler is blocked');
  await shot('05c-next-bowler');
  await pickFirstEnabled();
  await run(1); await run(1);
  await act('out'); await act('how', '[data-v="runOut"]');
  await act('roWho', '[data-v="nonStriker"]'); await act('roRuns', '[data-v="1"]'); await act('roConfirm');
  check((await sheet()).includes('Next batter'), 'run out -> next batter');
  await pickFirstEnabled();
  await run(3);
  const before = (await score()).replace(/\s/g, '');
  await act('undo');
  check((await score()).replace(/\s/g, '') !== before, 'undo removes the last ball');
  await run(1); await run(1);
  await noOverflow('scoring');
  await run(1);
  console.log('Innings 2');
  check((await app()).includes('Innings break'), 'innings break shown');
  check((await app()).includes('21 needed'), 'target 21 shown');
  await shot('06-innings-break', true);
  await openers();
  await run(6); await run(6); await run(6);
  await shot('06b-chase');
  await run(4);

  console.log('Result');
  const res = await app();
  check(/won by \d+ wickets?/.test(res), 'result: chasing side won by wickets');
  check(await page.isVisible('.potm-name'), 'performer of the match shown');
  check(res.includes('Continue with the same teams?'), 'rematch prompt shown');
  await noOverflow('result');
  await shot('07-result', true);
  await page.locator('[data-act="tab"]').nth(1).click();
  check((await page.textContent('.scorecard, .pane:last-child')).length > 0, 'scorecard tab switch');

  console.log('Poster');
  await act('poster');
  await page.waitForSelector('.poster-img', { timeout: 10000 });
  const src = await page.getAttribute('.poster-img', 'src');
  check(src && src.startsWith('data:image/png'), 'poster PNG generated');
  fs.writeFileSync(path.join(SHOTS, '08-poster-image.png'), Buffer.from(src.split(',')[1], 'base64'));
  await shot('08-poster');
  await act('backToResult');
  await act('rematch', '[data-v="same"]');
  check((await app()).includes('Series'), 'rematch goes straight to toss with series line');
  await shot('09-rematch-toss');

  console.log('Persistence + Kannada');
  await act('toRulesBack'); await act('toTeams'); await act('home');
  check((await app()).includes('#1'), 'history lists match #1');
  await act('settings');
  await act('lang', '[data-v="kn"]');
  await act('closeSheet');
  check((await app()).includes('ಗಲ್ಲಿ ಕ್ರಿಕೆಟ್'), 'Kannada UI');
  await shot('10-home-kn', true);
  await page.reload();
  await wait(300);
  check((await app()).includes('ಗಲ್ಲಿ ಕ್ರಿಕೆಟ್') && (await app()).includes('#1'), 'reload keeps language and history');
  await act('settings'); await act('lang', '[data-v="en"]'); await act('closeSheet');

  console.log('Tie -> bowl-out');
  await act('again');
  await act('call', '[data-v="T"]'); await act('caller', '[data-v="B"]');
  await act('realCoin');
  await act('landed', '[data-v="T"]');
  check((await app()).includes('won the toss'), 'real coin entry decides toss');
  await act('choice', '[data-v="bowl"]');
  await act('startMatch');
  await openers();
  await run(1);
  await act('menu'); await act('endInningsAsk'); await act('confirmYes');
  await openers();
  await run(1);
  await act('menu'); await act('endInningsAsk'); await act('confirmYes');
  check((await app()).includes('Scores level!'), 'tie screen');
  await shot('11-tie', true);
  await act('tiebreak', '[data-v="bowlout"]');
  await shot('12-bowlout');
  for (const v of ['1', '0', '1', '0', '1']) await act('bowl', '[data-v="' + v + '"]');
  check(!(await app()).includes('won the bowl-out'), 'bowl-out not decided while catch-up is possible');
  await act('bowl', '[data-v="0"]');
  check(/won the bowl-out 3–0/.test(await app()), 'bowl-out decided early (3–0 with 2 balls left)');

  console.log('Tie -> super over');
  await act('rematch', '[data-v="same"]');
  await act('call', '[data-v="H"]'); await act('caller', '[data-v="A"]'); await act('realCoin'); await act('landed', '[data-v="H"]');
  await act('choice', '[data-v="bat"]'); await act('startMatch');
  await openers(); await run(2); await act('menu'); await act('endInningsAsk'); await act('confirmYes');
  await openers(); await run(2); await act('menu'); await act('endInningsAsk'); await act('confirmYes');
  await act('tiebreak', '[data-v="super"]');
  check((await app()).includes('Super over 1'), 'super over openers');
  await openers(); await run(4); await act('menu'); await act('endInningsAsk'); await act('confirmYes');
  await openers(); await run(6);
  check(/won the super over/.test(await app()), 'super over decides the match');
  check((await page.locator('[data-act="tab"]').count()) === 4, 'scorecard has 4 innings tabs (2 + super over pair)');
  await act('resultMenu'); await act('settings'); await act('lang', '[data-v="kn"]'); await act('closeSheet');
  await act('poster');
  await page.waitForSelector('.poster-img', { timeout: 10000 });
  const srcKn = await page.getAttribute('.poster-img', 'src');
  fs.writeFileSync(path.join(SHOTS, '19-poster-kn.png'), Buffer.from(srcKn.split(',')[1], 'base64'));
  check(srcKn.startsWith('data:image/png'), 'Kannada poster renders');
  await act('backToResult');
  await act('resultMenu'); await act('settings'); await act('lang', '[data-v="en"]'); await act('closeSheet');

  console.log('Themes + looks');
  await act('resultMenu'); await act('settings'); await act('theme', '[data-v="light"]'); await act('closeSheet');
  await shot('13-result-light', true);
  await act('resultMenu'); await act('settings'); await act('glass', '[data-v="off"]'); await act('closeSheet');
  await shot('14-result-solid');
  await act('resultMenu'); await act('settings'); await act('glass', '[data-v="on"]'); await act('theme', '[data-v="auto"]'); await act('closeSheet');

  console.log('Small phone (320px) scoring');
  await act('rematch', '[data-v="same"]');
  await act('call', '[data-v="H"]'); await act('caller', '[data-v="A"]'); await act('realCoin'); await act('landed', '[data-v="H"]');
  await act('choice', '[data-v="bat"]'); await act('startMatch'); await openers();
  await run(1); await run(4); await run(6);
  await page.setViewportSize({ width: 320, height: 640 });
  await noOverflow('scoring @320px');
  await shot('15-scoring-320');
  await page.setViewportSize({ width: 390, height: 844 });
  await act('menu'); await act('settings'); await act('theme', '[data-v="light"]'); await act('closeSheet');
  await shot('16-scoring-light');
  await act('menu'); await act('settings'); await act('theme', '[data-v="auto"]'); await act('lang', '[data-v="kn"]'); await act('closeSheet');
  await act('mod', '[data-k="nb"]');
  await noOverflow('scoring Kannada');
  await shot('17-scoring-kn');
  await act('out');
  await shot('18-wicket-sheet-kn');
  await act('closeSheet');
  await act('menu'); await act('settings'); await act('lang', '[data-v="en"]'); await act('closeSheet');

  console.log('Single batter rule');
  await act('menu'); await act('abandonAsk'); await act('confirmYes');
  await act('again'); await act('toRulesBack');
  await act('setBool', '[data-k="singleBatter"][data-v="1"]');
  check(!(await page.isVisible('[data-act="toggleRule"][data-k="lastManStands"]')), 'last-man toggle hidden in single-batter mode');
  await shot('20-rules-single', true);
  await act('toToss');
  await act('call', '[data-v="H"]'); await act('caller', '[data-v="A"]'); await act('realCoin'); await act('landed', '[data-v="H"]');
  await act('choice', '[data-v="bat"]'); await act('startMatch');
  check(!(await page.isVisible('[data-act="opener"][data-k="nonStriker"]')), 'no non-striker picker in single-batter mode');
  await page.locator('[data-act="opener"][data-k="striker"]:not([disabled])').first().click();
  await page.locator('[data-act="opener"][data-k="bowler"]:not([disabled])').first().click();
  await act('startInnings');
  await run(1); await run(3);
  check((await page.locator('.crease .bat').count()) === 1, 'one batter at the crease');
  check(!(await page.isVisible('.swap-btn')), 'no swap button when batting alone');
  const solo = (await page.textContent('.crease .bname')).trim();
  await act('out'); await act('how', '[data-v="bowled"]');
  await pickFirstEnabled();
  check((await page.textContent('.crease .bname')).trim() !== solo && (await page.locator('.crease .bat').count()) === 1, 'next batter walks in alone');
  await shot('21-single-batter');

  console.log('No non-striker chip (two-batter rule)');
  await act('menu'); await act('abandonAsk'); await act('confirmYes');
  await act('again'); await act('toRulesBack');
  await act('setBool', '[data-k="singleBatter"][data-v="0"]');
  await act('toToss');
  await act('call', '[data-v="T"]'); await act('caller', '[data-v="B"]'); await act('realCoin'); await act('landed', '[data-v="T"]');
  await act('choice', '[data-v="bat"]'); await act('startMatch');
  await page.locator('[data-act="opener"][data-k="striker"]:not([disabled])').first().click();
  await act('opener', '[data-k="nonStriker"][data-id="__none__"]');
  await page.locator('[data-act="opener"][data-k="bowler"]:not([disabled])').first().click();
  await shot('22-openers-no-nonstriker', true);
  await act('startInnings');
  await run(1);
  check((await page.locator('.crease .bat').count()) === 1, '"No non-striker" starts the innings with one batter');

  console.log('Rematch: winner picks, no toss');
  await act('menu'); await act('endInningsAsk'); await act('confirmYes');
  await openers();
  await act('menu'); await act('endInningsAsk'); await act('confirmYes');
  const quick = await app();
  check(/won by 1 run/.test(quick), 'quick result for the rematch test');
  check(await page.isVisible('[data-act="rematch"][data-v="winner"]'), '"Yes, winner picks (no toss)" option shown');
  await shot('23-result-rematch-options');
  const winnerTeam = (quick.match(/(\S[^\n]*?) won by 1 run/) || [])[1];
  await act('rematch', '[data-v="winner"]');
  const nt = await app();
  check(/won the last match/.test(nt) && !(await page.isVisible('[data-act="call"]')), 'no-toss screen: winner picks, no heads/tails');
  await shot('24-no-toss');
  await act('choice', '[data-v="bowl"]'); await act('startMatch');
  const op = await app();
  check(/won the last match and chose to bowl/.test(op), 'openers show "won the last match and chose to bowl"');
  check(!op.includes(winnerTeam + ' batting') || !winnerTeam, 'winner chose bowl, so the other side bats first');
  await act('menu'); await act('abandonAsk'); await act('confirmYes');
  await page.locator('.row-item').first().click();
  await act('rematch', '[data-v="winner"]');
  await act('resetToss');
  check(await page.isVisible('[data-act="call"]'), '"Do a toss instead" returns to the normal toss');

  console.log('Home: play again, winner picks');
  await act('toRulesBack'); await act('toTeams'); await act('home');
  check(await page.isVisible('[data-act="againWinner"]'), 'home "again" card offers winner picks (no toss)');
  check((await page.textContent('[data-act="againWinner"]')).includes('Malleshwaram Mavericks'), 'it names the last winner');
  await shot('25-home-again-options');
  await act('againWinner');
  check(/Malleshwaram Mavericks won the last match/.test(await app()) && !(await page.isVisible('[data-act="call"]')), 'home winner-picks opens the no-toss screen');
  await act('choice', '[data-v="bat"]'); await act('startMatch');
  check(/won the last match and chose to bat/.test(await app()), 'match starts with the winner batting');

  check(errors.length === 0, 'no console errors' + (errors.length ? ': ' + errors.join(' | ') : ''));
  await browser.close();
  console.log('\n' + (failures.length ? failures.length + ' FAILED' : 'ALL PASSED'));
  process.exit(failures.length ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
